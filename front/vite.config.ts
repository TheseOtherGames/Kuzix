import path from 'node:path';
import { defineConfig, loadEnv, type Plugin } from 'vite';
import vue from '@vitejs/plugin-vue';

// Public, indexable routes. Everything else (dashboard, editor, games, profile) needs a login or a game code.
const PUBLIC_ROUTES = ['/', '/login', '/register'];
const PRIVATE_PREFIXES = ['/api/', '/auth/', '/dashboard', '/quizzes/', '/host/', '/play/', '/profile', '/admin'];

const seoFiles = (siteUrl: string): Plugin => ({
	name: 'kuzix-seo-files',
	transformIndexHtml: (html) => html.replaceAll('%SITE_URL%', siteUrl),
	generateBundle() {
		const today = new Date().toISOString().slice(0, 10);
		const files: Record<string, string> = {
			'sitemap.xml': `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${PUBLIC_ROUTES.map((route) => `\t<url><loc>${siteUrl}${route}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`,
			'robots.txt': `User-agent: *
${PRIVATE_PREFIXES.map((prefix) => `Disallow: ${prefix}`).join('\n')}

Sitemap: ${siteUrl}/sitemap.xml
`,
			'llms.txt': `# Kuzix

> Kuzix is a free real-time multiplayer quiz game. Create a quiz, host a live game on a big screen, and players join from their phone with a game code, pick an avatar and answer against the clock.

## Pages

- [Home](${siteUrl}/): join a game with its code, or start hosting
- [Log in](${siteUrl}/login): access your quizzes
- [Sign up](${siteUrl}/register): create an account to build and host quizzes

## Features

- Quiz editor with timed questions and 2 to 6 answers, one or more correct
- Import quizzes from JSON, including quizzes generated by an AI assistant from a prompt the app builds
- Live hosting: lobby, countdown, answer chart, leaderboard and podium
- Results per session, exportable as CSV
`,
		};
		for (const [fileName, source] of Object.entries(files)) {
			this.emitFile({ type: 'asset', fileName, source });
		}
	},
});

export default defineConfig(({ mode }) => {
	// Same FRONT_URL as the server (server/.env), so the generated links match where the app is served.
	const env = loadEnv(mode, path.resolve(import.meta.dirname, '../server'), '');
	const siteUrl = (env.FRONT_URL || 'http://localhost:3000').replace(/\/$/, '');

	return {
		root: import.meta.dirname,
		plugins: [vue(), seoFiles(siteUrl)],
		build: {
			target: 'baseline-widely-available',
			minify: 'oxc',
			cssMinify: 'lightningcss',
			sourcemap: false,
			emptyOutDir: true,
		},
		server: {
			proxy: {
				'/api': 'http://localhost:3000',
				'/ws': { target: 'ws://localhost:3000', ws: true },
			},
		},
	};
});
